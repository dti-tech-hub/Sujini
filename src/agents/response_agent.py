"""Response planning agent.

The plan is generated by deterministic policy, not by free-form LLM output.
"""
from __future__ import annotations

from typing import Any

from sqlalchemy.orm import Session

from src.database import repository
from src.database.models import Incident
from src.response.planner import ResponsePlanner
from src.utils.helpers import utcnow


class ResponseAgent:
    def __init__(self, session: Session) -> None:
        self.session = session

    def run(self, incident: Incident, *, risk_level: str, category: str) -> dict[str, Any]:
        repository.delete_actions_for_incident(self.session, incident.id)
        planner = ResponsePlanner()
        plan = planner.plan(
            incident_id=incident.id,
            risk_level=risk_level,
            category=category,
            source_ip=incident.source_ip,
            username=incident.username,
        )
        now = utcnow()
        records = []
        for action in plan.actions:
            status = {
                "auto": "APPROVED",
                "approval": "PENDING_APPROVAL" if action.requires_approval else "APPROVED",
                "advisory": "RECOMMENDED",
            }.get(action.policy_mode, "RECOMMENDED")
            record = repository.add_response_action(
                self.session,
                incident.id,
                action_type=action.action_type,
                description=action.description,
                risk_level=action.risk_level,
                requires_approval=action.requires_approval,
                policy_mode=action.policy_mode,
                status=status,
                parameters=action.parameters,
                is_simulated=action.is_simulated,
                recommendation_source=action.recommendation_source,
                approved_at=now if status == "APPROVED" else None,
                approved_by="policy_engine" if status == "APPROVED" else None,
            )
            records.append(record.to_dict())
        incident.approval_required = plan.approval_required
        incident.approval_status = "PENDING" if plan.approval_required else "NOT_REQUIRED"
        self.session.flush()
        payload = plan.to_dict()
        payload["actions"] = records
        return payload
